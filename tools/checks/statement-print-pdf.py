#!/usr/bin/env python3
"""Check actual Chromium PDF text, page bounds, embedded logo and pagination.
Requires PyMuPDF; artifacts generated by statement-print-browser.cjs, not live data.
"""
import collections
import pathlib
import re
import sys
import pymupdf

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.work/statement-print')
amounts = {'client-all': ['₹2,90,380', '₹89,584', '₹2,00,796'],
           'client-custom': ['₹2,90,280', '₹89,584', '₹2,00,696'],
           'vendor-all': ['¥70'],
           'client-large': ['₹12,34,63,889.12', '₹12,33,74,305.12']}
for name, expected in amounts.items():
    doc = pymupdf.open(root / f'{name}.pdf')
    text = '\n'.join(page.get_text() for page in doc)
    compact = re.sub(r'\s+', '', text)
    for amount in expected:
        assert amount in compact, (name, 'missing full amount', amount)
    assert 'Download' not in text and 'Filters' not in text and 'PAN ' not in text
    assert doc[0].get_images(), (name, 'missing embedded issuer logo')
    company = doc[0].search_for('MissPack India Pvt Ltd')[0]
    title = doc[0].search_for('STATEMENT OF ACCOUNT')[0]
    assert company.x1 < title.x0 and abs(company.y0 - title.y0) < 6
    lines = doc[0].get_text().splitlines()
    start = lines.index('MissPack India Pvt Ltd') + 1
    assert lines[start:start+3] == ['E-410, 4th Floor, City Centre',
        'Near Idgah Circle, Prem Darwaja Road, Idgah', 'Ahmedabad, Gujarat 380016, India'], (name, 'address not three visual lines')
    assert ('Payable' if name == 'vendor-all' else 'Receivable') in text
    if name == 'client-custom':
        assert '01 Jan 2025 – 31 Dec 2025' in text
    for page in doc:
        assert abs(page.rect.width - 595.28) < 1 and abs(page.rect.height - 841.89) < 1
        for x0, y0, x1, y1, *_ in page.get_text('words'):
            assert x0 >= 31 and x1 <= page.rect.width - 31 and y0 >= 31 and y1 <= page.rect.height - 31, (name, page.number, 'text outside A4 margins', (x0,y0,x1,y1))
    if name == 'client-large':
        assert 1 < len(doc) <= 3, '73-row fixture must exercise pagination without excessive paper use'
        assert collections.Counter(map(int,re.findall(r'PRINT-ROW-(\d+)',compact))) == collections.Counter(range(70)), 'A ledger row is missing or repeated'
        assert compact.count('ClosingReceivable') == 1, 'Closing balance must not repeat as a per-page footer'
        for page in doc:
            assert 'PARTICULARS' in page.get_text(), 'Table headings must repeat on each ledger page'
    doc[0].get_pixmap(matrix=pymupdf.Matrix(1.4,1.4)).save(root / f'{name}-paper.png')
    print(f'PASS {name}: {len(doc)} A4 page(s), complete amounts, three-line issuer address, loaded logo and page bounds')
