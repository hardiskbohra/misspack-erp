import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const cssRoot = path.join(repoRoot, 'resources', 'css');
const entryPath = path.join(cssRoot, 'master.css');
const outputPath = path.join(repoRoot, 'public', 'assets', 'css', 'design-system.css');
const importPattern = /^\s*@import\s+(['"])([^'"]+)\1\s*;\s*$/gm;

function expandStylesheet(filePath, stack = []) {
    const normalizedPath = path.resolve(filePath);
    if (!normalizedPath.startsWith(`${cssRoot}${path.sep}`) && normalizedPath !== entryPath) {
        throw new Error(`CSS import escapes resources/css: ${filePath}`);
    }
    if (stack.includes(normalizedPath)) {
        throw new Error(`Circular CSS import: ${[...stack, normalizedPath].map((file) => path.relative(repoRoot, file)).join(' -> ')}`);
    }

    const source = fs.readFileSync(normalizedPath, 'utf8');
    const nextStack = [...stack, normalizedPath];
    const expanded = source.replace(importPattern, (_match, _quote, request) => {
        if (!request.startsWith('.') || request.includes('?') || request.includes('#')) {
            throw new Error(`Only local relative CSS imports are supported: ${request} in ${path.relative(repoRoot, normalizedPath)}`);
        }

        let importedPath = path.resolve(path.dirname(normalizedPath), request);
        if (!path.extname(importedPath)) importedPath += '.css';
        if (!fs.existsSync(importedPath)) {
            throw new Error(`Missing CSS import ${request} in ${path.relative(repoRoot, normalizedPath)}`);
        }

        return `\n${expandStylesheet(importedPath, nextStack)}\n`;
    });

    return `/* --- ${path.relative(repoRoot, normalizedPath).replaceAll(path.sep, '/')} --- */\n${expanded.trim()}\n`;
}

const output = [
    '/* Generated from resources/css/master.css. Do not edit this file directly. */',
    '/* Refresh with: npm run build:design-system */',
    expandStylesheet(entryPath),
].join('\n\n');

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(`Generated ${path.relative(repoRoot, outputPath)} from resources/css/master.css`);
